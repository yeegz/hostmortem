#!/usr/bin/env python3
"""Generates the synthetic scenario fixtures in lab/fixtures/.

These are SYNTHETIC event streams shaped like real hmd output. They exercise
the detector and playbooks deterministically in CI. They are not recordings
of real faults; the live lab (lab/run_lab.sh) produces real ones.

Each file starts with '# expect:' which tests/integration/scenarios.sh checks.
"""
import json
import os
import random

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "fixtures")
SEC = 1_000_000_000
WALL0 = 1_794_000_000 * SEC  # 2026-11-08, arbitrary but fixed


class Stream:
    def __init__(self, seed):
        self.rng = random.Random(seed)
        self.events = []
        self.seq = {}
        self.boot = "b1-synthetic-0000-0000-000000000001"
        self.wall_offset = WALL0

    def reboot(self, boot_id, wall_jump_s):
        self.boot = boot_id
        self.wall_offset += wall_jump_s * SEC

    def emit(self, t, source, kind, severity="debug", subject="", **attrs):
        self.seq[(self.boot, source)] = self.seq.get((self.boot, source), 0) + 1
        mono = int(t * SEC)
        self.events.append({
            "v": 1, "boot_id": self.boot, "source": source, "seq": self.seq[(self.boot, source)],
            "mono_ns": mono, "wall_ns": self.wall_offset + mono, "wall_quality": "synced",
            "kind": kind, "severity": severity, "subject": subject, "attrs": attrs,
        })

    def status(self, t, **collectors):
        for name, state in collectors.items():
            name = name.replace("_", ".")
            attrs = {"state": state if isinstance(state, str) else state[0]}
            if not isinstance(state, str):
                attrs["reason"] = state[1]
            self.emit(t, "hmd", "collector.status", "info", name, **attrs)

    def start(self, t, kmsg="active"):
        self.emit(t, "hmd", "agent.start", "notice", "hmd", version="0.1.0-dev", kernel="6.8.0-synthetic")
        self.status(t, procfs="active", procfs_psi="active", procfs_conntrack="active", netlink="active",
                    kmsg=kmsg, prober="active", prober_icmp="active", prober_dns_direct="active", process="active")

    def background(self, t0, t1, *, gw_ok=True, resolver_ok=True, direct_ok=True, rtt=1.2, target_rtt=12.0,
                   retrans_ppm=400.0, psi_cpu=1.0, psi_mem=0.0, tcp_ok=True):
        t = t0
        while t < t1:
            self.emit(t, "procfs", "sys.cpu", subject="cpu", busy_pct=round(self.rng.uniform(3, 9), 1))
            self.emit(t, "procfs", "sys.psi", subject="psi", cpu_some10=psi_cpu, mem_some10=psi_mem,
                      mem_full10=psi_mem / 2, io_some10=0.5)
            self.emit(t, "procfs", "net.tcp", subject="tcp", out_segs=2400, retrans_segs=int(2400 * retrans_ppm / 1e6),
                      retrans_ppm=retrans_ppm, attempt_fails=0, estab_resets=0, timeouts=0 if retrans_ppm < 10000 else 4)
            self.emit(t, "procfs", "net.conntrack", subject="conntrack", insert_failed=0, drop=0, early_drop=0)
            if int(t) % 10 == 0:
                self.probe_round(t + 0.2, gw_ok, resolver_ok, direct_ok, rtt, target_rtt, tcp_ok)
            t += 5

    def probe_round(self, t, gw_ok, resolver_ok, direct_ok, rtt, target_rtt, tcp_ok):
        sev = lambda ok: "debug" if ok else "warning"
        self.emit(t, "prober", "probe.dns.resolver", sev(resolver_ok), "resolver", ok=resolver_ok, name="example.com",
                  latency_ms=4.0 if resolver_ok else 5000.0,
                  **({} if resolver_ok else {"err": "Temporary failure in name resolution"}))
        self.emit(t + 0.05, "prober", "probe.dns.direct", sev(direct_ok), "192.0.2.53", ok=direct_ok,
                  server="192.0.2.53", name="example.com", latency_ms=8.0 if direct_ok else 2000.0,
                  **({"rcode": "NOERROR"} if direct_ok else {"err": "timeout"}))
        self.emit(t + 0.1, "prober", "probe.icmp", sev(gw_ok), "192.0.2.1", ok=gw_ok, target="192.0.2.1",
                  role="gateway", rtt_ms=rtt if gw_ok else 2000.0, **({} if gw_ok else {"err": "timeout"}))
        self.emit(t + 0.15, "prober", "probe.icmp", "debug", "198.51.100.7", ok=True, target="198.51.100.7",
                  role="target", rtt_ms=target_rtt)
        self.emit(t + 0.2, "prober", "probe.tcp", sev(tcp_ok), "198.51.100.7:443", ok=tcp_ok,
                  target="198.51.100.7:443", latency_ms=20.0 if tcp_ok else 2000.0,
                  **({} if tcp_ok else {"err": "timeout"}))

    def write(self, name, expect):
        path = os.path.join(OUT, name + ".jsonl")
        with open(path, "w") as f:
            f.write(f"# SYNTHETIC fixture generated by lab/gen_fixtures.py - not a recording\n")
            f.write(f"# expect: {expect}\n")
            for e in self.events:
                f.write(json.dumps(e, separators=(",", ":")) + "\n")


def scenario(name, expect, build, seed=1):
    s = Stream(seed)
    s.start(100)
    s.background(100, 700)  # 10 minutes of healthy baseline
    build(s)
    s.write(name, expect)


def dns_local(s):
    s.background(700, 760, resolver_ok=False)
    s.background(760, 1000)


def dns_upstream(s):
    s.background(700, 760, resolver_ok=False, direct_ok=False)
    s.background(760, 1000)


def gateway_disconnect(s):
    s.emit(700, "netlink", "link.state", "warning", "eth0", ifname="eth0", ifindex=2, oper="down", up=True,
           carrier=False, initial=False)
    s.emit(700.1, "netlink", "route.del", "warning", "default", default=True, family="ipv4", gateway="192.0.2.1",
           ifname="eth0", initial=False)
    s.background(700, 760, gw_ok=False, resolver_ok=False, direct_ok=False, tcp_ok=False)
    s.emit(760, "netlink", "link.state", "info", "eth0", ifname="eth0", ifindex=2, oper="up", up=True,
           carrier=True, initial=False)
    s.background(760, 1000)


def kill9(s):
    s.emit(700, "process", "process.start", "info", "app", name="app", pid=4100)
    s.emit(730, "process", "process.exit", "warning", "app", name="app", pid=4100)
    s.background(700, 900)


def missing_kmsg(s):
    s.status(650, kmsg=("unavailable", "open /dev/kmsg: EPERM (needs CAP_SYSLOG, or kernel.dmesg_restrict=0)"))
    s.emit(730, "process", "process.exit", "warning", "app", name="app", pid=4100)
    s.background(700, 900)


def oom(s):
    s.background(700, 720, psi_mem=45.0)
    s.emit(721, "kernel", "kernel.oom", "error", "app", pid=4100, comm="app", memcg=True, ts_source="printk")
    s.emit(721.5, "process", "process.exit", "warning", "app", name="app", pid=4100)
    s.emit(722.5, "process", "process.restart", "warning", "app", name="app", old_pid=4100, new_pid=4188)
    s.background(720, 900)


def restart_loop(s):
    pid = 5000
    for i in range(5):
        s.emit(700 + i * 12, "process", "process.exit", "warning", "worker", name="worker", pid=pid)
        s.emit(701 + i * 12, "process", "process.restart", "warning", "worker", name="worker", old_pid=pid, new_pid=pid + 1)
        pid += 1
    s.background(700, 900)


def clock_step(s):
    s.emit(700, "procfs", "clock.step", "warning", "realtime", step_ms=-86_400_000)
    s.emit(700.1, "procfs", "clock.state", "notice", "realtime", synced=False, quality="unsynced", max_error_us=16_000_000)
    s.background(700, 740, tcp_ok=False)
    s.background(740, 900)


def retrans_storm(s):
    s.background(700, 760, retrans_ppm=62000.0)
    s.background(760, 950)


def latency_spike(s):
    s.background(700, 790, target_rtt=310.0, tcp_ok=False)
    s.background(790, 1000)


def reboot_mid_incident(s):
    # Upstream DNS fails, then the box is hard-reset; the new boot's wall
    # clock starts unsynchronised. The incident must span both boots.
    s.background(700, 740, resolver_ok=False, direct_ok=False)
    s.reboot("b2-synthetic-0000-0000-000000000002", wall_jump_s=-3600 * 24 * 365)
    s.start(8)
    s.emit(8.5, "procfs", "clock.state", "notice", "realtime", synced=False, quality="unsynced", max_error_us=16_000_000)
    s.background(10, 40, resolver_ok=False, direct_ok=False)
    s.background(40, 300)


def resource_pressure(s):
    s.background(700, 760, psi_cpu=92.0)
    s.background(760, 950)


def nic_stall(s):
    s.emit(700, "kernel", "kernel.netdev_watchdog", "error", "eth0", ifname="eth0", ts_source="printk")
    s.background(700, 740, gw_ok=False, resolver_ok=False, direct_ok=False)
    s.background(740, 900)


if __name__ == "__main__":
    os.makedirs(OUT, exist_ok=True)
    scenario("dns_local_path", "leading=local_resolver ruled_out=link_or_gateway", dns_local)
    scenario("dns_upstream", "leading=upstream_dns ruled_out=local_resolver,link_or_gateway", dns_upstream)
    scenario("gateway_disconnect", "leading=link_or_gateway ruled_out=upstream_dns,local_resolver", gateway_disconnect)
    scenario("process_kill9", "leading=unknown ruled_out=oom_kill possible=process_exit", kill9)
    scenario("missing_kmsg", "leading=unknown possible=oom_kill", missing_kmsg)
    scenario("oom_kill", "leading=oom_kill", oom)
    scenario("restart_loop", "leading=restart_loop", restart_loop)
    scenario("clock_step", "leading=clock_step", clock_step)
    scenario("retrans_storm", "leading=retrans_storm", retrans_storm)
    scenario("latency_spike", "leading=path_degradation", latency_spike)
    scenario("reboot_mid_incident", "leading=upstream_dns ruled_out=local_resolver", reboot_mid_incident)
    scenario("cpu_saturation", "leading=resource_pressure", resource_pressure)
    scenario("nic_stall", "leading=nic_stall", nic_stall)
    print("fixtures written to", OUT)
